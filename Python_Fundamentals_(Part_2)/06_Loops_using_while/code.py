# while loop : print "hello world" for 5 times

count = 1 # this is known as 'iterator' and iterator mostly named as i, j, k

while (count <= 5):
  print("hello world", count)
  count = count + 1        # we can also write like : count += 1

print("after loop, count = ", count) #6

'''
Output: 

hello world 1
hello world 2
hello world 3
hello world 4
hello world 5
'''