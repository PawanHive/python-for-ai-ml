# range (stop)

for i in range(5):
  print(i)

'''
output:
0
1
2
3
4
'''

# range (start, stop)

for i in range(1, 5):
  print(i)

'''
output:
1
2
3
4
'''

# range (start, stop, step)
## here 'step' means how much to increase/decrease each time

for i in range(0, 10, 2):
  print(i)

'''
output:
0
2
4
6
8
'''